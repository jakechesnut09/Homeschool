#!/usr/bin/env python3
"""Build the data files for the static web app in web/.

Writes web/data/index.json (grades, course summaries, reference data) and
web/data/grade_XX.json (full course content, loaded on demand).

Usage:  python3 scripts/build_web.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
OUT = ROOT / "web" / "data"

# Links in the app point at this repository branch.
REPO = "https://github.com/jakechesnut09/Homeschool"
BRANCH = "main"

GRADES = {
    1: ("Elementary", "A Child's Place in Time and Space"),
    2: ("Elementary", "People Who Make a Difference"),
    3: ("Elementary", "Continuity and Change"),
    4: ("Elementary", "California: A Changing State"),
    5: ("Elementary", "U.S. History: Making a New Nation"),
    6: ("Middle", "Ancient Civilizations"),
    7: ("Middle", "Medieval and Early Modern Times"),
    8: ("Middle", "U.S. History: Growth and Conflict"),
    9: ("High", "World Geography & Ethnic Studies"),
    10: ("High", "The Modern World"),
    11: ("High", "U.S. History in the 20th Century"),
    12: ("High", "American Democracy & Economics"),
}
SUBJECTS = [
    ("ELA", "English Language Arts"), ("MATH", "Mathematics"), ("SCI", "Science"),
    ("HSS", "History–Social Science"), ("WL", "World Language"), ("VAPA", "Visual & Performing Arts"),
    ("PE", "Physical Education"), ("HEALTH", "Health"), ("ELEC", "Elective"),
]
ORDER = {code: i for i, (code, _) in enumerate(SUBJECTS)}


def load(p):
    return json.loads(p.read_text(encoding="utf-8"))


def dump(obj, p):
    p.write_text(json.dumps(obj, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    grades = []
    for g, (band, theme) in GRADES.items():
        files = sorted((DATA / "curriculum" / f"grade_{g:02d}").glob("*.json"),
                       key=lambda p: ORDER.get(p.stem, 99))
        courses_full, summaries = [], []
        for f in files:
            c = load(f)
            c["source"] = f"data/curriculum/grade_{g:02d}/{f.name}"
            courses_full.append(c)
            summaries.append({
                "subject": c["subject"], "title": c["title"], "minutes": c.get("minutes_per_day"),
                "ag": c.get("ag_requirement"), "credits": c.get("credits"), "units": len(c["units"]),
            })
        dump({"grade": g, "courses": courses_full}, OUT / f"grade_{g:02d}.json")
        grades.append({"grade": g, "band": band, "theme": theme, "courses": summaries})

    ref = DATA / "reference"
    index = {
        "repo": REPO, "branch": BRANCH,
        "subjects": [{"code": c, "name": n} for c, n in SUBJECTS],
        "grades": grades,
        "legal": load(ref / "legal_options.json"),
        "paperwork": load(ref / "paperwork.json"),
        "funding": load(ref / "funding.json"),
        "resources": load(ref / "resources.json"),
    }
    dump(index, OUT / "index.json")

    # web/index.html = web/app.html wrapped in a full document (for GitHub Pages / any static host).
    app = (ROOT / "web" / "app.html").read_text(encoding="utf-8")
    (ROOT / "web" / "index.html").write_text(
        "<!doctype html>\n<!-- Generated by scripts/build_web.py from web/app.html. Edit app.html, not this file. -->\n"
        '<html lang="en">\n<head>\n<meta charset="utf-8">\n'
        '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n'
        + app.replace("<header", "</head>\n<body>\n<header", 1) + "\n</body>\n</html>\n", encoding="utf-8")
    total = sum(p.stat().st_size for p in OUT.glob("*.json"))
    print(f"Wrote {len(list(OUT.glob('*.json')))} files to {OUT} ({total / 1e6:.1f} MB)")


if __name__ == "__main__":
    main()
